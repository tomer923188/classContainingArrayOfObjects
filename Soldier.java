	public class Soldier {
		private String name;
		private double height;

	//constructor
	public Soldier(String name, double height) {
		this.name = name;
		this.height = height;
		}

	//returns the soldier's name
	public String getName() {
		return name;
	}
	//returns the soldier's height
	public double getHeight() {
		return height;
		}
	}